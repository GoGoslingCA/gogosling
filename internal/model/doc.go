// Package model 定义内核各模块共享的领域类型、错误码与仓储接口。
//
// 本包是叶子包：只依赖标准库，不包含任何行为逻辑（除 ID 生成与错误辅助函数）。
// 所有跨模块传递的数据都用这里的类型表达，避免各包各自定义一套再互相转换。
//
// 约定：
//   - 公开标识一律是字符串 ULID（见 NewID），数据库主键也直接用它。
//   - 时间统一为 UTC 的 time.Time；序列化为 RFC 3339。
//   - 需要持久化但结构会演进的字段（Parts、Manifest、Details）用 JSON 存储。
//   - 修改本包是架构层面的决定：新增字段必须向后兼容，删除字段需要迁移。
package model
